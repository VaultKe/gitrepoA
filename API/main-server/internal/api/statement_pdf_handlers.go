// DownloadChamaSubscriptionReport — GET /chamas/:id/subscription-payments/report
func DownloadChamaSubscriptionReport(c *gin.Context) {
	chamaID, ok := requireParam(c, "id", "Chama ID is required")
	if !ok {
		return
	}
	userID := c.GetString("userID")
	db := dbFromContext(c)
	if db == nil {
		return
	}

	var isMember bool
	if err := db.QueryRow(
		"SELECT EXISTS(SELECT 1 FROM chama_members WHERE chama_id = $1 AND user_id = $2 AND COALESCE(is_active, true))",
		chamaID, userID,
	).Scan(&isMember); err != nil || !isMember {
		c.JSON(http.StatusForbidden, gin.H{"success": false, "error": "You are not a member of this chama"})
		return
	}

	var chamaName string
	_ = db.QueryRow("SELECT COALESCE(name,'') FROM chamas WHERE id = $1", chamaID).Scan(&chamaName)
	if chamaName == "" {
		chamaName = "Chama"
	}

	rows, err := db.Query(`
		SELECT COALESCE(month_year,''), due_date, paid_at, COALESCE(payment_method,''),
		       COALESCE(amount,0), COALESCE(status,''), COALESCE(transaction_id,'')
		FROM subscription_payments
		WHERE chama_id = $1
		ORDER BY due_date
	`, chamaID)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"success": false, "error": "Failed to read subscription payments"})
		return
	}
	defer rows.Close()

	type subRec struct {
		month, method, status, txn string
		due                        time.Time
		paid                       *time.Time
		amount                     float64
	}
	var recs []subRec
	var totalBilled, totalPaid float64
	for rows.Next() {
		var r subRec
		if rows.Scan(&r.month, &r.due, &r.paid, &r.method, &r.amount, &r.status, &r.txn) != nil {
			continue
		}
		recs = append(recs, r)
		totalBilled += r.amount
		if strings.EqualFold(r.status, "paid") || r.paid != nil {
			totalPaid += r.amount
		}
	}

	pdf, genAt := newStatementPDF(chamaName, "Subscription Payments Statement", "")

	pdf.SetFont("Helvetica", "B", 13)
	pdf.CellFormat(120, 8, "Subscriptions", "", 0, "L", false, 0, "")
	pdf.Ln(11)

	sectionTitle(pdf, "Summary")
	outstanding := totalBilled - totalPaid
	if outstanding < 0 {
		outstanding = 0
	}
	kvGrid(pdf, [][2]string{
		{"Total billed", money(totalBilled)},
		{"Total paid", money(totalPaid)},
		{"Outstanding", money(outstanding)},
		{"Records", fmt.Sprintf("%d", len(recs))},
	})
	pdf.Ln(3)

	sectionTitle(pdf, "Payments")
	if len(recs) == 0 {
		emptyLine(pdf, "No subscription payments recorded for this chama.")
	} else {
		w := []float64{26, 28, 28, 32, 34, 30}
		tableHeader(pdf, []string{"Month", "Due", "Paid on", "Method", "Amount", "Status"}, w)
		for i, r := range recs {
			paidOn := "—"
			if r.paid != nil && !r.paid.IsZero() {
				paidOn = r.paid.Format("2 Jan 2006")
			}
			tableRow(pdf, []string{
				orDash(r.month),
				r.due.Format("2 Jan 2006"),
				paidOn,
				title(orDash(r.method)),
				money(r.amount),
				title(orDash(r.status)),
			}, w, i%2 == 1)
		}
	}

	statementDisclaimer(pdf, chamaName, genAt)
	writeStatementPDF(c, pdf, fmt.Sprintf("subscription-statement-%s.pdf", safeFilePart(chamaID)))
}

