var stmtCreditTypes = map[string]bool{
	"contribution": true, "deposit": true, "welfare_contribution": true,
	"loan_payment": true, "loan_repayment": true, "subscription": true,
	"service_fee": true, "share_purchase": true, "shares": true, "merry-go-round": true,
}

// DownloadChamaTransactionsReport — GET /chamas/:id/transactions/report?scope=personal|group|member&memberId=&limit=
func DownloadChamaTransactionsReport(c *gin.Context) {
	chamaID, ok := requireParam(c, "id", "Chama ID is required")
	if !ok {
		return
	}
	userID := c.GetString("userID")
	db := dbFromContext(c)
	if db == nil {
		return
	}

	var role string
	if err := db.QueryRow(
		"SELECT lower(COALESCE(role,'')) FROM chama_members WHERE chama_id = $1 AND user_id = $2 AND COALESCE(is_active, true)",
		chamaID, userID,
	).Scan(&role); err != nil {
		c.JSON(http.StatusForbidden, gin.H{"success": false, "error": "You are not a member of this chama"})
		return
	}
	isOfficer := role == "chairperson" || role == "treasurer" || role == "secretary" || role == "admin"

	scope := strings.ToLower(c.DefaultQuery("scope", "personal"))
	memberID := c.Query("memberId")
	if (scope == "group" || scope == "all" || scope == "member") && !isOfficer {
		c.JSON(http.StatusForbidden, gin.H{"success": false, "error": "Only the chairperson, treasurer or secretary can export group records"})
		return
	}

	limit := 500
	if v, err := strconv.Atoi(c.Query("limit")); err == nil && v > 0 {
		limit = v
	}
	if limit > 3000 {
		limit = 3000
	}

	var chamaName string
	_ = db.QueryRow("SELECT COALESCE(name,'') FROM chamas WHERE id = $1", chamaID).Scan(&chamaName)
	if chamaName == "" {
		chamaName = "Chama"
	}

	q := `
		SELECT t.created_at, COALESCE(t.type,''), COALESCE(t.description,''),
		       COALESCE(t.amount,0), COALESCE(t.status,''), COALESCE(t.reference,''),
		       TRIM(COALESCE(u.first_name,'') || ' ' || COALESCE(u.last_name,''))
		FROM transactions t
		LEFT JOIN users u ON u.id = t.initiated_by
		WHERE t.chama_id = $1`
	args := []interface{}{chamaID}
	subject := "Group statement"
	switch scope {
	case "personal", "":
		q += ` AND (t.initiated_by = $2 OR t.recipient_id = $2)`
		args = append(args, userID)
		subject = "Personal statement"
	case "member":
		if memberID == "" {
			c.JSON(http.StatusBadRequest, gin.H{"success": false, "error": "memberId is required for a member statement"})
			return
		}
		q += ` AND (t.initiated_by = $2 OR t.recipient_id = $2)`
		args = append(args, memberID)
		var mn string
		_ = db.QueryRow("SELECT TRIM(COALESCE(first_name,'') || ' ' || COALESCE(last_name,'')) FROM users WHERE id = $1", memberID).Scan(&mn)
		if strings.TrimSpace(mn) != "" {
			subject = "Statement for " + strings.TrimSpace(mn)
		}
	}
	q += fmt.Sprintf(` ORDER BY t.created_at DESC LIMIT %d`, limit)

	rows, err := db.Query(q, args...)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"success": false, "error": "Failed to read transactions"})
		return
	}
	defer rows.Close()

	type txRec struct {
		at                            time.Time
		kind, desc, status, ref, name string
		amount                        float64
	}
	var recs []txRec
	var credit, debit float64
	for rows.Next() {
		var r txRec
		if rows.Scan(&r.at, &r.kind, &r.desc, &r.amount, &r.status, &r.ref, &r.name) != nil {
			continue
		}
		recs = append(recs, r)
		if stmtCreditTypes[strings.ToLower(r.kind)] {
			credit += r.amount
		} else {
			debit += r.amount
		}
	}

	pdf, genAt := newStatementPDF(chamaName, "Transactions Statement", "")

	pdf.SetFont("Helvetica", "B", 13)
	pdf.CellFormat(120, 8, subject, "", 0, "L", false, 0, "")
	pdf.Ln(11)

	sectionTitle(pdf, "Summary")
	kvGrid(pdf, [][2]string{
		{"Inflows", money(credit)},
		{"Outflows", money(debit)},
		{"Net", money(credit - debit)},
		{"Transactions", fmt.Sprintf("%d", len(recs))},
		{"Period end", genAt.Format("2 Jan 2006")},
		{"", ""},
	})
	pdf.Ln(3)

	sectionTitle(pdf, "Transactions")
	if len(recs) == 0 {
		emptyLine(pdf, "No transactions found for the selected scope.")
	} else {
		w := []float64{24, 24, 50, 30, 28, 22}
		tableHeader(pdf, []string{"Date", "Type", "Description", "By", "Amount", "Status"}, w)
		for i, r := range recs {
			desc := r.desc
			if strings.TrimSpace(desc) == "" {
				desc = orDash(r.ref)
			}
			tableRow(pdf, []string{
				r.at.Format("2 Jan 06"),
				title(orDash(r.kind)),
				desc,
				orDash(r.name),
				money(r.amount),
				title(orDash(r.status)),
			}, w, i%2 == 1)
		}
	}

	statementDisclaimer(pdf, chamaName, genAt)
	writeStatementPDF(c, pdf, fmt.Sprintf("transactions-statement-%s-%s.pdf", safeFilePart(chamaID), scope))
}
