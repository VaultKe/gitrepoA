// Table-based PDF statements, generated server-side with gofpdf in the same
// visual language as the loan report (header band, section rules, zebra tables,
// standard footer). These replace the client-side HTML-to-print receipts.

// newStatementPDF returns an A4 portrait document carrying the standard VaultKe
// header band and footer.
func newStatementPDF(orgName, docTitle, ref string) (*gofpdf.Fpdf, time.Time) {
	pdf := gofpdf.New(gofpdf.OrientationPortrait, "mm", "A4", "")
	pdf.SetMargins(16, 18, 16)
	pdf.SetAutoPageBreak(true, 22)
	genAt := time.Now()

	pdf.SetFooterFunc(func() {
		pdf.SetY(-15)
		pdf.SetDrawColor(rpHair[0], rpHair[1], rpHair[2])
		pdf.SetLineWidth(0.2)
		pdf.Line(16, pdf.GetY(), 194, pdf.GetY())
		pdf.Ln(2)
		pdf.SetFont("Helvetica", "", 7)
		pdf.SetTextColor(rpMuted[0], rpMuted[1], rpMuted[2])
		left := fmt.Sprintf("(c) %d %s. Generated by the %s platform on behalf of %s.",
			genAt.Year(), loanReportAppName, loanReportAppName, sanitize(orgName))
		pdf.CellFormat(150, 4, left, "", 0, "L", false, 0, "")
		pdf.CellFormat(28, 4, fmt.Sprintf("Page %d of {nb}", pdf.PageNo()), "", 0, "R", false, 0, "")
	})
	pdf.AliasNbPages("{nb}")
	pdf.AddPage()

	pdf.SetFillColor(rpBand[0], rpBand[1], rpBand[2])
	pdf.Rect(0, 0, 210, 30, "F")
	pdf.SetXY(16, 7)
	pdf.SetFont("Helvetica", "B", 16)
	pdf.SetTextColor(255, 255, 255)
	pdf.CellFormat(120, 8, sanitize(orgName), "", 2, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(190, 200, 214)
	pdf.CellFormat(120, 5, docTitle, "", 2, "L", false, 0, "")
	pdf.SetXY(120, 9)
	pdf.SetFont("Helvetica", "", 8)
	pdf.CellFormat(74, 4, "Generated "+genAt.Format("2 Jan 2006, 15:04"), "", 2, "R", false, 0, "")
	if strings.TrimSpace(ref) != "" {
		pdf.CellFormat(74, 4, "Ref "+ref, "", 2, "R", false, 0, "")
	}

	pdf.SetY(38)
	pdf.SetTextColor(rpInk[0], rpInk[1], rpInk[2])
	return pdf, genAt
}

func statementDisclaimer(pdf *gofpdf.Fpdf, orgName string, genAt time.Time) {
	pdf.Ln(7)
	pdf.SetFont("Helvetica", "I", 7.5)
	pdf.SetTextColor(rpMuted[0], rpMuted[1], rpMuted[2])
	pdf.MultiCell(0, 4,
		fmt.Sprintf("This statement is issued by %s and reflects the records held as at %s. It is a computer-generated document and does not require a signature. \"%s\" and the %s wordmark are the property of the %s platform.",
			sanitize(orgName), genAt.Format("2 Jan 2006 15:04 MST"), loanReportAppName, loanReportAppName, loanReportAppName),
		"", "L", false)
	pdf.SetTextColor(rpInk[0], rpInk[1], rpInk[2])
}

func writeStatementPDF(c *gin.Context, pdf *gofpdf.Fpdf, filename string) {
	var buf strings.Builder
	if err := pdf.Output(strWriter{&buf}); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"success": false, "error": "Failed to render statement"})
		return
	}
	c.Header("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
	c.Data(http.StatusOK, "application/pdf", []byte(buf.String()))
}

func safeFilePart(s string) string {
	var b strings.Builder
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '-' {
			b.WriteRune(r)
		} else {
			b.WriteRune('-')
		}
	}
	out := strings.Trim(b.String(), "-")
	if out == "" {
		out = "vaultke"
	}
	return out
}

